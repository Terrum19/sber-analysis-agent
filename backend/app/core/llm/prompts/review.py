REVIEW_PROMPT = """Агент ответил на вопрос пользователя по данным. Проверь исследование.

{evidence}

Пройди чек-лист. Для каждого пункта: id, status (ok — проблемы нет; issue — проблема есть;
n/a — к этому вопросу не относится) и evidence — на что из данных выше ты опираешься
(числа, шаги, колонки). Пункты:
{checks}

Правила:
- Опирайся только на данные выше. Нет в уликах — не выдумывай.
- Проблема material, только если её исправление может изменить заголовок или вывод
  ответа: другое число, другой лидер, другой знак тренда, другой ответ «да/нет».
  Иначе minor. У material обязательно evidence из данных выше.
- Неиспользованная колонка — проблема, только если она прямо относится к вопросу
  (вопрос про выручку, а посчитано число заказов при наличии колонки суммы).
  «Можно ещё разрезать по региону» — не проблема.
- Выбросы — проблема, если среднее заметно отличается от медианы и вывод держится на среднем
  или на одном экстремальном значении.
- Неполный крайний период, сравниваемый с полными, — material для вывода о росте/падении.
- Причинность, тренд по двум точкам, «значимо» без теста — проблема claims.
- Отрицательные значения метрики (возвраты, списания, отмены с минусом) при SUM уже
  вычитаются: сумма без фильтра — чистая. Исключить такие строки — значит получить
  валовую сумму, она больше, а не меньше. «Не исключены возвраты — завышено» верно,
  только если у возвратов значения метрики положительные (видно по доле отрицательных).
- Ответ за другой период или в другой единице, чем спрошено (по месяцам вместо суммы
  за квартал, за день вместо за неделю, штуки вместо рублей), — проблема
  answers_question, material.

Для каждой проблемы: check (id пункта), severity, message (что не так, одной фразой),
evidence, fix (что сделать, одной фразой).

verdict:
- ok — проблем нет или только minor, о которых не стоит говорить;
- caveat — ответ годный, но пользователю нужна оговорка (caveats — короткие фразы);
- fix_insight — данные и расчёт верны, но вывод сформулирован неверно или утверждает лишнее;
  исправленный вывод использует только числа, которые уже есть в результате ответа
  и фактах по нему;
- extend_plan — расчёт верен, но не хватает проверки или расчёта (медиана при выбросах,
  доля вместо числа, исключение неполного периода, учёт нужной колонки): дополнить план
  новыми шагами. Если для исправления нужно число, которого нет в результате ответа
  (медиана, доля, период по исходной таблице), — это extend_plan, а не fix_insight:
  число должен посчитать шаг;
- replan — неверна основа: не та метрика, колонка, таблица или период; план заново.
Выбирай самое лёгкое действие, которое исправит material-проблемы.
"""

