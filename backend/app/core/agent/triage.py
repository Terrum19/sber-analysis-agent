"""Реплики без запроса к данным: приветствие, благодарность, «что ты умеешь».

Раньше любая реплика шла в планировщик: «привет» получал план из нескольких
шагов и график или, при пустом плане, ошибку «не удалось подобрать
инструменты». Такие реплики узнаются целиком (короткие, без слов о данных)
и получают готовый ответ без LLM, SQL и графика.
"""

import re

GREETING = "Здравствуйте! Задайте вопрос о данных, например: «Какая выручка по месяцам?»"
THANKS = "Пожалуйста! Если нужно, задайте следующий вопрос о данных."
ACK = "Хорошо. Если нужно, задайте следующий вопрос о данных."
HELP = (
    "Я отвечаю на вопросы о подключённой таблице: считаю итоги и средние, "
    "группирую по категориям и периодам, ищу выбросы и тренды, проверяю "
    "статистические гипотезы и строю графики. Спросите, например: "
    "«Топ-5 клиентов по сумме» или «Есть ли тренд выручки?»"
)

# Реплика целиком: вежливость и пунктуация вокруг, больше ничего.
_POLITE = r"(?:ну|и|а|ок|окей|ладно|хорошо|понятно|ясно|отлично|спс|вам|тебе|большое|огромное|очень|друг|коллега|бот)"
_PATTERNS = (
    (GREETING, r"(?:привет\w*|здравствуй\w*|здорово|добр\w+ (?:утро|день|вечер)|хай|hi|hello)"),
    (THANKS, r"(?:спасибо|спасиб\w*|благодар\w*|thanks?|thx)"),
    (ACK, r"(?:ок|окей|ok|okay|хорошо|понятно|ясно|отлично|супер)"),
    (HELP, r"(?:что ты (?:умеешь|можешь)|что умеешь|помощь|help|кто ты|ты кто)"),
)
_FILLER = rf"(?:\s+{_POLITE})*"
_MATCHERS = [
    (reply, re.compile(rf"^(?:{_POLITE}\s+)*{core}{_FILLER}$", re.IGNORECASE))
    for reply, core in _PATTERNS
]


def small_talk_reply(question: str) -> str | None:
    """Готовый ответ, если реплика — не вопрос к данным; иначе None."""
    text = re.sub(r"[^\w\s-]", " ", question).strip().lower()
    text = re.sub(r"\s+", " ", text)
    for reply, matcher in _MATCHERS:
        if matcher.match(text):
            return reply
    return None
