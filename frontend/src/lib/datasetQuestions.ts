/**
 * Генерация релевантных аналитических вопросов под структуру и домен датасета.
 * Модель формирует вопросы на основе названия таблицы, колонок и профиля данных.
 */
export function getDatasetQuestions(
  table?: string,
  databaseTitle?: string,
  profileSummary?: string
): string[] {
  if (!table) {
    return [
      "Создай дашборд с ключевыми показателями",
      "Сравни динамику показателей по периодам",
    ];
  }

  const tLower = table.toLowerCase();
  const dbLower = (databaseTitle || "").toLowerCase();
  const sumLower = (profileSummary || "").toLowerCase();
  const combined = `${tLower} ${dbLower} ${sumLower}`;

  // 1. Энергетика / Электроэнергия / Мощность
  if (/electric|price|volume|energy|generation|power|grid|hour|load|мвт|гвт|рсв|электр|генерац/i.test(combined)) {
    return [
      "Покажи почасовую динамику выработки и цен на электроэнергию",
      "Сравни объемы генерации и найди пиковые часы нагрузки",
      "Построй сводный дашборд по рынкам РСВ и индексам мощности",
    ];
  }

  // 2. Клиенты / Пользователи / Аудитория
  if (/customer|user|client|audience|subscriber|loyalt|клиент|пользовател/i.test(combined)) {
    return [
      "Сделай сегментацию клиентов по частоте и активности",
      "Какова динамика удержания и активности аудитории?",
      "Построй дашборд по ключевым когортам и LTV пользователей",
    ];
  }

  // 3. Товары / Склад / Ассортимент
  if (/product|item|inventory|good|catalog|stock|товар|номенклатур|склад/i.test(combined)) {
    return [
      "Какие товары приносят максимальную маржу и оборот?",
      "Покажи распределение ассортимента по ценовым категориям",
      "Построй сводную панель по остаткам и оборачиваемости товаров",
    ];
  }

  // 4. Финансы / Платежи / Транзакции
  if (/finance|transaction|payment|billing|invoice|bank|деньг|платеж|транзакц|банк/i.test(combined)) {
    return [
      "Покажи динамику финансовых поступлений и структуру расходов",
      "Сравни средний размер транзакций и выяви аномальные операции",
      "Сформируй финансовый дашборд с ключевыми метриками периода",
    ];
  }

  // 5. Продажи / Заказы / Ритейл
  if (/sale|order|revenue|purchase|retail|чек|продаж|заказ|выручк/i.test(combined)) {
    return [
      "Создай дашборд по регионам и выручке от продаж",
      "Сравни структуру выручки по категориям товаров",
      "Покажи динамику среднего чека и ключевые KPI",
    ];
  }

  // 6. Любой пользовательский датасет (универсальная генерация)
  const cleanName = table.replace(/[_-]/g, " ");
  return [
    `Построй сводный дашборд с ключевыми метриками по таблице «${cleanName}»`,
    `Покажи динамику и распределение основных показателей в «${cleanName}»`,
    `Выяви аномалии, выбросы и тренды в данных «${cleanName}»`,
  ];
}
